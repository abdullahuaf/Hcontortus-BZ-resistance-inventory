def fetch_genbank_record(accession):
    """Fetch GenBank record from NCBI using accession number."""
    print(f"Fetching GenBank record for accession: {accession} ...")
    with Entrez.efetch(db="nucleotide", id=accession, rettype="gb", retmode="text") as handle:
        record = SeqIO.read(handle, "genbank")
    print(f"Successfully fetched: {accession}")
    return record

def sequence_to_fasta(record, line_length=60):
    """Convert sequence to FASTA format string with wrapped lines, including version and definition."""
    header = f">{record.id} {record.description}"
    seq = str(record.seq)
    wrapped_seq = "\n".join(seq[i:i+line_length] for i in range(0, len(seq), line_length))
    return f"{header}\n{wrapped_seq}"


def extract_flat_fields(record):
    """Extract flat fields from GenBank record."""
    print(f"Extracting flat fields for {record.id} ...")
    flat = {
        "accession": record.id,
        "version": record.annotations.get("accessions", [""])[0],
        "definition": record.description,
        "length": len(record.seq),
        "organism": record.annotations.get("organism", ""),
        "taxonomy": "; ".join(record.annotations.get("taxonomy", [])),
        "topology": record.annotations.get("topology", ""),
        "date": record.annotations.get("date", ""),
        "keywords": "; ".join(record.annotations.get("keywords", [])),
        "sequence_fasta": sequence_to_fasta(record)  # Added sequence in FASTA format here
    }
    print("Flat fields extracted.")
    return flat

def extract_features(record):
    """Extract all qualifiers from features like source, CDS, gene, etc."""
    print(f"Extracting features for {record.id} ...")
    features_data = defaultdict(str)

    for feature in record.features:
        for key, value in feature.qualifiers.items():
            joined = "; ".join(value)
            # Make a unique column name: featureType_qualifierKey
            colname = f"{feature.type}_{key}"
            if colname in features_data:
                features_data[colname] += ", " + joined
            else:
                features_data[colname] = joined
    print("Features extracted.")
    return features_data

def extract_references(record):
    """Extract all references (authors, title, journal, etc)."""
    print(f"Extracting references for {record.id} ...")
    refs = {}
    for i, ref in enumerate(record.annotations.get("references", []), 1):
        refs[f"ref{i}_authors"] = "; ".join(ref.authors) if ref.authors else ""
        refs[f"ref{i}_title"] = ref.title or ""
        refs[f"ref{i}_journal"] = ref.journal or ""
        refs[f"ref{i}_pubmed"] = getattr(ref, "pubmed_id", "")
    print("References extracted.")
    return refs

def genbank_to_excel(accessions, output_file):
    all_rows = []

    print(f"Starting processing of {len(accessions)} accession(s)...\n")
    for i, acc in enumerate(accessions, 1):
        print(f"Processing {i}/{len(accessions)}: {acc}")
        try:
            record = fetch_genbank_record(acc)
        except Exception as e:
            print(f"Failed to fetch {acc}: {e}\nSkipping to next accession...\n")
            continue

        flat = extract_flat_fields(record)
        features = extract_features(record)
        references = extract_references(record)

        full_data = {**flat, **features, **references}
        all_rows.append(full_data)
        print(f"Finished processing {acc}\n{'-'*40}")

    print("All records processed, compiling Excel file...")
    df = pd.DataFrame(all_rows)
    df.to_excel(output_file, index=False)
    print(f"✅ Excel file saved as: {output_file}")

